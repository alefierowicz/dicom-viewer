import json
from pathlib import Path

import numpy as np

OUT = Path(__file__).resolve().parent / "data"
OUT.mkdir(exist_ok=True)

volumes = {
    # name: (array, slope, intercept)
    "i16_2x3x4": (np.arange(24, dtype="<i2").reshape(2, 3, 4), 1.0, 0.0),
    # CT-like: raw 0..4095, physical = raw - 1024  ->  -1024..3071
    "u16_ct_3x64x64": (
        np.random.default_rng(0).integers(0, 4096, size=(3, 64, 64)).astype("<u2"),
        1.0,
        -1024.0,
    ),
    "f32_1x4x5": (np.linspace(-1, 1, 20, dtype="<f4").reshape(1, 4, 5), 1.0, 0.0),
}

DTYPE = {"<i2": "i16", "<u2": "u16", "<f4": "f32"}

for name, (arr, slope, intercept) in volumes.items():
    path = OUT / f"{name}.raw"
    arr.tofile(path)  # raw bytes, C-order, no header
    cmd = {
        "cmd": "load",
        "path": str(path),
        "dtype": DTYPE[arr.dtype.str],
        "shape": list(arr.shape),
        "slope": slope,
        "intercept": intercept,
    }
    phys = arr.astype(np.float64) * slope + intercept
    print(f"# {name}: {path.stat().st_size} bytes, expected min {phys.min()}, max {phys.max()}")
    print(json.dumps(cmd))